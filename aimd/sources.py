# ----------------------------------------------------------------------------- MuseBench (Liu et al. 2026, arXiv 2610.20310)

MB = "https://huggingface.co/datasets/Anonymousv22222/MuseBench-part{p}/resolve/main/part{p}_{k:03d}.tar"


def _mb_base(member: str) -> str:
    name = member.rsplit("/", 1)[-1]
    return name[:-4] if name.lower().endswith(".wav") else name


def mb_group(member: str, human: bool = False) -> str:
    """Leakage group for a MuseBench file.

    MuseBench conditions every open generator on captions of the same human tracks, so all
    clips made from one source artist's captions - and that artist's own Jamendo tracks -
    must land on the same side of every split.
    """
    base = _mb_base(member)
    stem = base[:-4] if base.lower().endswith(".mp3") else base
    if human or "/Jamedo/" in member or member.startswith("Jamendo/"):
        artist = stem.rsplit(" - ", 1)[-1] if " - " in stem else stem
        artist = re.sub(r"_\d{4,}$", "", artist.strip())  # JamendoMaxCaps suffix on colliding names
        return f"mb_jamendo_artist:{artist.lower()}"
    # Genius-Lyrics captions: "<title>_<artist>_<11-char youtube id>"; the id itself may contain '_'
    core = re.sub(r"_[A-Za-z0-9_-]{11}$", "", stem)
    artist = core.rsplit("_", 1)[-1] if "_" in core else core
    return f"mb_genius_artist:{artist.strip().lower()}"


def _fetch_musebench(src: Source, scale: float, prefix: str, shards: list[tuple[int, int]], generator: str,
                     vocal_hint, find: bool = False, human: bool = False) -> None:
    """Stream ~n/len(shards) files of one MuseBench folder from each listed (part, shard)."""
    from .fetch import tar_find_offset

    n = int(src.n * scale)
    per = -(-n // len(shards))
    rows = []
    for p, k in shards:
        url = MB.format(p=p, k=k)
        state = src.raw / f"p{p}_{k:03d}.state.json"
        start = 0
        if find and not state.exists():
            start = tar_find_offset(url, prefix)
        kept = stream_tar(url, src.raw, max_samples=per, keep_ext={".wav", ".mp3"}, state_file=state,
                          prefix=prefix, start_offset=start, hash_names=True)
        for item in kept:
            base = _mb_base(item["member"])
            aid = mb_group(item["member"], human)
            rows.append({"file": item["file"], "track_id": f"{src.name}:{item['stem']}", "artist_id": aid,
                         "generator": generator, "genre": "", "tags": item["member"][:200], "title": base[:120],
                         "vocal_hint": vocal_hint, "created": "2026 (MuseBench)", "member": item["member"]})
    _write_meta(src, rows[:n])


